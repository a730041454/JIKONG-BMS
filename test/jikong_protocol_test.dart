void main() {
  test('切帧：300 字节固定长度 + CRC@299 校验', () {
    final buf = <int>[0x41, 0x54, 0x0d, 0x0a, ..._capturedCellFrame, 0x41, 0x54];
    final frame = JkProtocol.tryTakeFrame(buf);
    expect(frame, isNotNull);
    expect(frame!.length, 300);
    expect(frame[2], 0xEB);
    expect(frame[4], JkProtocol.typeCell);
    // 剩余字节保留在缓冲区，供下次拼帧
    expect(buf, [0x41, 0x54]);
  });

  test('真实帧解析：16 串 / 53.846V / SOC 78 / 40Ah / 放电 MOS 开', () {
    final c = JkParser.parseCell(_capturedCellFrame);
    expect(c.cellVoltages.length, 32);
    expect(c.cellVoltages[0], closeTo(3.367, 0.0005));
    expect(c.cellVoltages[7], closeTo(3.359, 0.0005));
    expect(c.cellVoltages[15], closeTo(3.366, 0.0005));
    expect(c.cellVoltages[16], 0);
    expect(c.maxCellIdx, 0);
    expect(c.minCellIdx, 7);
    expect(c.avgCellV, closeTo(3.365, 0.0005));
    expect(c.deltaV, closeTo(0.008, 0.0005));
    expect(c.totalVoltage, closeTo(53.846, 0.0005));
    expect(c.current, closeTo(0, 0.0005));
    expect(c.soc, closeTo(78, 1e-9));
    expect(c.remainingAh, closeTo(31.127, 0.0005));
    expect(c.nominalAh, closeTo(40, 0.0005));
    expect(c.cycles, 0); // 该帧 @182 = 0（新板未记循环），SOH @190 = 100%
    expect(c.chargeMos, isFalse);
    expect(c.dischargeMos, isTrue);
    expect(c.balancingActive, isFalse);
    expect(c.temperatures, hasLength(5));
    expect(c.temperatures[0], closeTo(20.8, 0.05));
    expect(c.temperatures.every((x) => x > -10 && x < 60), isTrue);
  });

  test('写命令帧：放电 MOS 0x1E len=4 + 校验和', () {
    final f = JkProtocol.buildDischargeMos(true);
    expect(f.length, 20);
    expect(f.sublist(0, 10), [0xAA, 0x55, 0x90, 0xEB, 0x1E, 0x04, 0x01, 0, 0, 0]);
    var sum = 0;
    for (var i = 0; i < 19; i++) {
      sum += f[i];
    }
    expect(f[19], sum & 0xFF);
  });

  test('串数/容量写入寄存器为 0x1C / 0x20', () {
    final cells = JkProtocol.buildWriteCellCount(16);
    expect(cells[4], 0x1C);
    expect(cells.sublist(6, 10), [16, 0, 0, 0]);

    final cap = JkProtocol.buildWriteCapacity(40);
    expect(cap[4], 0x20);
    expect(cap.sublist(6, 10), [0x40, 0x9C, 0x00, 0x00]);
  });

  test('设置帧解析：开关使能位 + 参数表', () {
    final s = JkParser.parseSettings(_capturedSettingsFrame);
    expect(s.cellCount, 16);
    expect(s.capacityAh, closeTo(100.0, 0.001));
    expect(s.chargeEnabled, isTrue);
    expect(s.dischargeEnabled, isTrue);
    expect(s.balanceEnabled, isTrue);
    expect(s.values['vp_uv'], closeTo(2.5, 1e-6));
    expect(s.values['vp_ocv'], closeTo(3.65, 1e-6));
    expect(s.values['bal_dv'], closeTo(0.010, 1e-6));
    expect(s.values['tp_cltp'], closeTo(-40.0, 1e-6));
    expect(s.values['bal_cur'], closeTo(0.6, 1e-6));
  });

  test('参数写帧：按系数换算并按定义选长度', () {
    final f = JkProtocol.buildWriteParam(jkParamDef('vp_uv')!, 2.5);
    expect(f.length, 20);
    expect(f[4], 0x02);
    expect(f.sublist(6, 10), [0xC4, 0x09, 0, 0]);
    var sum = 0;
    for (var i = 0; i < 19; i++) {
      sum += f[i];
    }
    expect(f[19], sum & 0xFF);
  });
}
